static const u8 aes_rcon[11] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,
};

static u8 aes_xtime(u8 a) { return (u8)((a << 1) ^ ((a & 0x80) ? 0x1b : 0)); }

static u8 aes_gmul(u8 a, u8 b)
{
    u8 p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1)
            p ^= a;
        a = aes_xtime(a);
        b >>= 1;
    }
    return p;
}

void aes128_set_key(aes128_ctx_t *ctx, const u8 key[16])
{
    memcpy(ctx->rk, key, 16);
    u8 *rk = ctx->rk;
    for (int i = 4; i < 44; i++) {
        u8 tmp[4];
        memcpy(tmp, rk + (i - 1) * 4, 4);
        if (i % 4 == 0) {
            u8 t = tmp[0];
            tmp[0] = aes_sbox[tmp[1]] ^ aes_rcon[i / 4];
            tmp[1] = aes_sbox[tmp[2]];
            tmp[2] = aes_sbox[tmp[3]];
            tmp[3] = aes_sbox[t];
        }
        for (int j = 0; j < 4; j++)
            rk[i * 4 + j] = rk[(i - 4) * 4 + j] ^ tmp[j];
    }
}

static void aes_add_round_key(u8 s[16], const u8 rk[16])
{
    for (int i = 0; i < 16; i++)
        s[i] ^= rk[i];
}

static void aes_sub_bytes(u8 s[16])
{
    for (int i = 0; i < 16; i++)
        s[i] = aes_sbox[s[i]];
}

static void aes_shift_rows(u8 s[16])
{
    u8 t;
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

static void aes_mix_columns(u8 s[16])
{
    for (int c = 0; c < 4; c++) {
        u8 *col = s + c * 4;
        u8 a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
        col[0] = (u8)(aes_gmul(a0, 2) ^ aes_gmul(a1, 3) ^ a2 ^ a3);
        col[1] = (u8)(a0 ^ aes_gmul(a1, 2) ^ aes_gmul(a2, 3) ^ a3);
        col[2] = (u8)(a0 ^ a1 ^ aes_gmul(a2, 2) ^ aes_gmul(a3, 3));
        col[3] = (u8)(aes_gmul(a0, 3) ^ a1 ^ a2 ^ aes_gmul(a3, 2));
    }
}

/* state is column-major (byte i lands in column i/4, row i%4) --
   matches the key schedule above's own per-column word operations */
void aes128_encrypt_block(const aes128_ctx_t *ctx, const u8 in[16], u8 out[16])
{
    u8 s[16];
    memcpy(s, in, 16);
    aes_add_round_key(s, ctx->rk);
    for (int round = 1; round <= 9; round++) {
        aes_sub_bytes(s);
        aes_shift_rows(s);
        aes_mix_columns(s);
        aes_add_round_key(s, ctx->rk + round * 16);
    }
    aes_sub_bytes(s);
    aes_shift_rows(s);
    aes_add_round_key(s, ctx->rk + 10 * 16);
    memcpy(out, s, 16);
}

/* ---- GHASH / AES-128-GCM (NIST SP 800-38D) ----------------------------
 *
 * Only ever used here with a 12-byte (96-bit) IV -- the case TLS
 * always uses, and the case SP 800-38D gives a direct construction
 * for (J0 = IV || 0^31 || 1) rather than needing the general
 * GHASH-the-IV path for other IV lengths. */

static void gf128_mul(const u8 x[16], const u8 y[16], u8 out[16])
{
    u8 z[16] = {0};
    u8 v[16];
    memcpy(v, y, 16);
    for (int i = 0; i < 128; i++) {
        int bit = (x[i / 8] >> (7 - i % 8)) & 1;
        if (bit)
            for (int j = 0; j < 16; j++)
                z[j] ^= v[j];
        int lsb = v[15] & 1;
        for (int j = 15; j > 0; j--)
            v[j] = (u8)((v[j] >> 1) | ((v[j - 1] & 1) << 7));
        v[0] = (u8)(v[0] >> 1);
        if (lsb)
            v[0] ^= 0xe1;
    }
    memcpy(out, z, 16);
}

typedef struct {
    u8 h[16];
    u8 y[16];
} ghash_ctx_t;

static void ghash_init(ghash_ctx_t *g, const u8 h[16])
{
    memcpy(g->h, h, 16);
    memset(g->y, 0, 16);
}

static void ghash_update_block(ghash_ctx_t *g, const u8 block[16])
{
    u8 xored[16];
    for (int i = 0; i < 16; i++)
        xored[i] = g->y[i] ^ block[i];
    gf128_mul(xored, g->h, g->y);
}

static void ghash_update(ghash_ctx_t *g, const u8 *data, u32 len)
{
    while (len >= 16) {
        ghash_update_block(g, data);
        data += 16;
        len -= 16;
    }
    if (len) {
        u8 block[16] = {0};
        memcpy(block, data, len);
        ghash_update_block(g, block);
    }
}

static void put_u64_be(u8 *p, u64 v)
{
    for (int i = 0; i < 8; i++)
        p[i] = (u8)(v >> (56 - i * 8));
}

/* advances only bytes [12,16) of the 16-byte counter block, per SP
   800-38D's 32-bit incrementing function inc32() -- the fixed prefix
   (J0's IV + block-counter-starts-at-1 byte) never changes */
static void gcm_inc32(u8 counter[16])
{
    for (int i = 15; i >= 12; i--)
        if (++counter[i])
            break;
}

void aes128_gcm_encrypt(const aes128_ctx_t *ctx, const u8 iv[12],
                        const u8 *aad, u32 aad_len, const u8 *pt, u32 pt_len,
                        u8 *ct, u8 tag[16])
{
    u8 h[16] = {0};
    aes128_encrypt_block(ctx, h, h);

    u8 j0[16];
    memcpy(j0, iv, 12);
    j0[12] = 0; j0[13] = 0; j0[14] = 0; j0[15] = 1;

    u8 counter[16];
    memcpy(counter, j0, 16);
    gcm_inc32(counter); /* encryption starts at J0+1; J0 itself is
                            reserved for the tag mask below */

    u32 off = 0;
    while (off < pt_len) {
        u8 ks[16];
        aes128_encrypt_block(ctx, counter, ks);
        u32 n = pt_len - off < 16 ? pt_len - off : 16;
        for (u32 i = 0; i < n; i++)
            ct[off + i] = pt[off + i] ^ ks[i];
        off += n;
        gcm_inc32(counter);
    }

    ghash_ctx_t g;
    ghash_init(&g, h);
    ghash_update(&g, aad, aad_len);
    ghash_update(&g, ct, pt_len);
    u8 lenblock[16];
    put_u64_be(lenblock, (u64)aad_len * 8);
    put_u64_be(lenblock + 8, (u64)pt_len * 8);
    ghash_update_block(&g, lenblock);

    u8 s[16];
    aes128_encrypt_block(ctx, j0, s);
    for (int i = 0; i < 16; i++)
        tag[i] = g.y[i] ^ s[i];
}

/* Returns true iff the tag verifies -- pt is only ever the correctly
   decrypted plaintext when this returns true; callers must never look
   at pt otherwise. CTR-mode decryption only runs after the tag check
   passes (no "decrypt speculatively, check after" -- an attacker who
   can observe *how far* garbage decryption proceeded before being
   discarded gains nothing here, since it simply never starts). */
bool aes128_gcm_decrypt(const aes128_ctx_t *ctx, const u8 iv[12],
                        const u8 *aad, u32 aad_len, const u8 *ct, u32 ct_len,
                        const u8 tag[16], u8 *pt)
{
    u8 h[16] = {0};
    aes128_encrypt_block(ctx, h, h);

    u8 j0[16];
    memcpy(j0, iv, 12);
    j0[12] = 0; j0[13] = 0; j0[14] = 0; j0[15] = 1;

    ghash_ctx_t g;
    ghash_init(&g, h);
    ghash_update(&g, aad, aad_len);
    ghash_update(&g, ct, ct_len);
    u8 lenblock[16];
    put_u64_be(lenblock, (u64)aad_len * 8);
    put_u64_be(lenblock + 8, (u64)ct_len * 8);
    ghash_update_block(&g, lenblock);

    u8 s[16];
    aes128_encrypt_block(ctx, j0, s);
    u8 computed_tag[16];
    for (int i = 0; i < 16; i++)
        computed_tag[i] = g.y[i] ^ s[i];

    /* every byte compared regardless of an early mismatch, rather
       than a short-circuiting memcmp, so this doesn't leak timing
       about *where* the tag diverged */
    u8 diff = 0;
    for (int i = 0; i < 16; i++)
        diff |= (u8)(computed_tag[i] ^ tag[i]);
    if (diff != 0)
        return false;

    u8 counter[16];
    memcpy(counter, j0, 16);
    gcm_inc32(counter);
    u32 off = 0;
    while (off < ct_len) {
        u8 ks[16];
        aes128_encrypt_block(ctx, counter, ks);
        u32 n = ct_len - off < 16 ? ct_len - off : 16;
        for (u32 i = 0; i < n; i++)
            pt[off + i] = ct[off + i] ^ ks[i];
        off += n;
        gcm_inc32(counter);
    }
    return true;
}

/* ---- big-integer arithmetic (for RSA verify + P-256 ECDHE) ------------
 *
 * Fixed-width, BN_LIMBS 32-bit limbs, little-endian (limb[0] is least
 * significant) -- 4096 bits, comfortably covering both an RSA-4096
 * modulus and (using only its low 8 limbs) P-256's 256-bit field.
 * Every operation here processes the full fixed width regardless of
 * the "real" size of its operands: simpler and easier to get right
 * than a variable-length representation, and performance doesn't
 * matter here -- this runs once per TLS handshake, not in a hot loop.
 *
 * bn_modexp() is also how modular inverse is computed (via Fermat's
 * little theorem, a^(p-2) mod p, valid whenever p is prime) rather
 * than a separate extended-Euclidean implementation -- one less
 * algorithm to get right, reusing code already verified elsewhere in
 * this section.
 *
 * (BN_LIMBS and bignum_t itself are declared in kernel.h, not here,
 * since ecdhe/rsa/x509 code elsewhere needs the type too.)
 */

void bn_zero(bignum_t *r) { memset(r->limb, 0, sizeof(r->limb)); }

void bn_from_bytes_be(bignum_t *r, const u8 *data, u32 len)
{
    bn_zero(r);
    for (u32 i = 0; i < len; i++) {
        u32 byte_idx = len - 1 - i;
        u32 limb_idx = i / 4;
        u32 shift = (i % 4) * 8;
        if (limb_idx < BN_LIMBS)
            r->limb[limb_idx] |= (u32)data[byte_idx] << shift;
    }
}

void bn_to_bytes_be(const bignum_t *a, u8 *out, u32 out_len)
{
    for (u32 i = 0; i < out_len; i++) {
        u32 byte_idx = out_len - 1 - i;
        u32 limb_idx = i / 4;
        u32 shift = (i % 4) * 8;
        out[byte_idx] = limb_idx < BN_LIMBS ? (u8)(a->limb[limb_idx] >> shift) : 0;
    }
}

int bn_cmp(const bignum_t *a, const bignum_t *b)
{
    for (int i = BN_LIMBS - 1; i >= 0; i--) {
        if (a->limb[i] != b->limb[i])
            return a->limb[i] > b->limb[i] ? 1 : -1;
    }
    return 0;
}

bool bn_is_zero(const bignum_t *a)
{
    for (int i = 0; i < BN_LIMBS; i++)
        if (a->limb[i])
            return false;
    return true;
}

/* r = a + b; returns the carry out (0 or 1) */
u32 bn_add(bignum_t *r, const bignum_t *a, const bignum_t *b)
{
    u64 carry = 0;
    for (int i = 0; i < BN_LIMBS; i++) {
        u64 s = (u64)a->limb[i] + b->limb[i] + carry;
        r->limb[i] = (u32)s;
        carry = s >> 32;
    }
    return (u32)carry;
}

/* r = a - b; assumes a >= b everywhere this is called (every call
   site in this file establishes that beforehand -- see e.g.
   bn_mod_wide's own invariant comment) */
u32 bn_sub(bignum_t *r, const bignum_t *a, const bignum_t *b)
{
    u64 borrow = 0;
    for (int i = 0; i < BN_LIMBS; i++) {
        u64 ai = a->limb[i];
        u64 bi = (u64)b->limb[i] + borrow;
        if (ai >= bi) {
            r->limb[i] = (u32)(ai - bi);
            borrow = 0;
        } else {
            r->limb[i] = (u32)((ai + ((u64)1 << 32)) - bi);
            borrow = 1;
        }
    }
    return (u32)borrow;
}

/* shift left by 1 bit in place; returns the bit shifted out the top */
static u32 bn_shl1(bignum_t *a)
{
    u32 carry = 0;
    for (int i = 0; i < BN_LIMBS; i++) {
        u32 new_carry = a->limb[i] >> 31;
        a->limb[i] = (a->limb[i] << 1) | carry;
        carry = new_carry;
    }
    return carry;
}

/* full a*b into a 2*BN_LIMBS-limb little-endian result */
static void bn_mul_wide(u32 *r, const bignum_t *a, const bignum_t *b)
{
    memset(r, 0, sizeof(u32) * BN_LIMBS * 2);
    for (int i = 0; i < BN_LIMBS; i++) {
        if (a->limb[i] == 0)
            continue;
        u64 carry = 0;
        for (int j = 0; j < BN_LIMBS; j++) {
            u64 p = (u64)a->limb[i] * b->limb[j] + r[i + j] + carry;
            r[i + j] = (u32)p;
            carry = p >> 32;
        }
        int k = i + BN_LIMBS;
        while (carry) {
            u64 s = (u64)r[k] + carry;
            r[k] = (u32)s;
            carry = s >> 32;
            k++;
        }
    }
}

/* Highest set bit position + 1 (i.e. the number of significant bits);
   0 if a is zero. Every loop below is bounded by this instead of the
   fixed BN_LIMBS width -- without that, every operation costs the
   same whether the real operands are 17 bits (RSA's e=65537), 256
   bits (a P-256 scalar), or the full 4096-bit width, which measured
   over 2 *seconds per modexp call* natively during this file's own
   development (let alone under QEMU's CPU emulation, where it hung
   past a 20-second boot timeout entirely). With this bound, the same
   two realistic shapes measured under 25ms each. */
static u32 bn_bit_length(const bignum_t *a)
{
    for (int i = BN_LIMBS - 1; i >= 0; i--) {
        if (a->limb[i]) {
            u32 v = a->limb[i];
            u32 bits = 0;
            while (v) { bits++; v >>= 1; }
            return (u32)i * 32 + bits;
        }
    }
    return 0;
}

/* wide_a mod n -> r (BN_LIMBS limbs): binary long division, one bit
   of wide_a at a time, MSB to LSB, processing only the top_bits
   significant bits of wide_a (see bn_bit_length()'s comment above).
   rem stays < n before every shift (loop invariant, true initially
   since rem starts at 0 and n > 0), so after shifting left by 1 bit
   rem is < 2n -- which fits in BN_LIMBS limbs without overflow as
   long as n itself uses fewer than the full BN_LIMBS*32 bits (true
   for every modulus this file ever calls this with: RSA moduli up to
   4096 bits and P-256's 256-bit prime both leave headroom in a
   4096-bit-wide bignum_t) */
static void bn_mod_wide(bignum_t *r, const u32 *wide_a, u32 top_bits,
                        const bignum_t *n)
{
    bignum_t rem;
    bn_zero(&rem);
    for (int bit = (int)top_bits - 1; bit >= 0; bit--) {
        u32 limb_idx = (u32)bit / 32;
        u32 bitpos = (u32)bit % 32;
        u32 in_bit = (wide_a[limb_idx] >> bitpos) & 1;
        bn_shl1(&rem);
        rem.limb[0] |= in_bit;
        if (bn_cmp(&rem, n) >= 0)
            bn_sub(&rem, &rem, n);
    }
    *r = rem;
}

void bn_mulmod(bignum_t *r, const bignum_t *a, const bignum_t *b,
              const bignum_t *n)
{
    /* a and b are always already-reduced (< n) at every call site in
       this file (bn_modexp's own loop invariant), so their product
       has at most 2*bitlen(n) significant bits -- an upper bound
       that's always safe here without computing the wide product's
       exact bit length */
    u32 wide[BN_LIMBS * 2];
    bn_mul_wide(wide, a, b);
    u32 bound = 2 * bn_bit_length(n);
    if (bound > BN_LIMBS * 2 * 32)
        bound = BN_LIMBS * 2 * 32;
    bn_mod_wide(r, wide, bound, n);
}

void bn_modexp(bignum_t *r, const bignum_t *base, const bignum_t *exp,
              const bignum_t *n)
{
    bignum_t result, b;
    bn_zero(&result);
    result.limb[0] = 1;

    /* reduce base mod n first, in case base >= n */
    u32 wide[BN_LIMBS * 2];
    memset(wide, 0, sizeof(wide));
    memcpy(wide, base->limb, sizeof(base->limb));
    bn_mod_wide(&b, wide, bn_bit_length(base), n);

    u32 exp_bits = bn_bit_length(exp); /* exp==0 -> 0 iterations -> result
                                           stays 1, i.e. x^0 == 1 */
    for (u32 i = 0; i < exp_bits; i++) {
        u32 limb_idx = i / 32, bitpos = i % 32;
        if ((exp->limb[limb_idx] >> bitpos) & 1)
            bn_mulmod(&result, &result, &b, n);
        if (i + 1 < exp_bits) /* skip the last, useless squaring -- b
                                  is never read again after this */
            bn_mulmod(&b, &b, &b, n);
    }
    *r = result;
}

/* modular inverse via Fermat's little theorem -- ONLY valid when n is
   prime (every call site in this codebase uses this exclusively for
   P-256's field prime, never for an RSA modulus, which is never
   prime) */
void bn_modinv_prime(bignum_t *r, const bignum_t *a, const bignum_t *p)
{
    bignum_t two, p_minus_2;
    bn_zero(&two);
    two.limb[0] = 2;
    bn_sub(&p_minus_2, p, &two);
    bn_modexp(r, a, &p_minus_2, p);
}

/* ---- self-test: known-answer vectors, checked at boot -------------------
 *
 * This isn't a "just in case" belt-and-suspenders check: crypto bugs
 * are exactly the kind that don't announce themselves the way a bad
 * PE bounds check does (a panic, a fault, an obviously wrong pixel).
 * A wrong hash or a subtly wrong PRF produces output that looks like
 * a hash or PRF output and is silently useless or worse. Every
 * primitive TLS depends on is re-verified here, at runtime, on the
 * actual compiled kernel code -- not just "the host prototype passed"
 * -- every time AlphaOS boots, before anything is ever allowed to
 * trust it for a real connection.
 */
static bool bytes_eq(const u8 *a, const u8 *b, u32 n)
{
    for (u32 i = 0; i < n; i++)
        if (a[i] != b[i])
            return false;
    return true;
}

bool crypto_selftest(void)
{
    u8 out[48];

    /* SHA-256("") */
    static const u8 sha_empty[32] = {
        0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
        0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55,
    };
    sha256((const u8 *)"", 0, out);
    if (!bytes_eq(out, sha_empty, 32))
        return false;

    /* SHA-256("abc") */
    static const u8 sha_abc[32] = {
        0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
        0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad,
    };
    sha256((const u8 *)"abc", 3, out);
    if (!bytes_eq(out, sha_abc, 32))
        return false;

    /* HMAC-SHA256(key=0x0b*20, "Hi There") -- RFC 4231 test case 1 */
    static const u8 hmac_expect[32] = {
        0xb0,0x34,0x4c,0x61,0xd8,0xdb,0x38,0x53,0x5c,0xa8,0xaf,0xce,0xaf,0x0b,0xf1,0x2b,
        0x88,0x1d,0xc2,0x00,0xc9,0x83,0x3d,0xa7,0x26,0xe9,0x37,0x6c,0x2e,0x32,0xcf,0xf7,
    };
    u8 key[20];
    memset(key, 0x0b, 20);
    hmac_sha256(key, 20, (const u8 *)"Hi There", 8, out);
    if (!bytes_eq(out, hmac_expect, 32))
        return false;

    /* HMAC-SHA256(key="Jefe", "what do ya want for nothing?")
       -- RFC 4231 test case 2 */
    static const u8 hmac_expect2[32] = {
        0x5b,0xdc,0xc1,0x46,0xbf,0x60,0x75,0x4e,0x6a,0x04,0x24,0x26,0x08,0x95,0x75,0xc7,
        0x5a,0x00,0x3f,0x08,0x9d,0x27,0x39,0x83,0x9d,0xec,0x58,0xb9,0x64,0xec,0x38,0x43,
    };
    hmac_sha256((const u8 *)"Jefe", 4, (const u8 *)"what do ya want for nothing?",
               28, out);
    if (!bytes_eq(out, hmac_expect2, 32))
        return false;

    /* TLS 1.2 PRF, cross-checked against an independent from-scratch
       Python implementation of RFC 5246 section 5 (not a published
       IETF/NIST vector, since P_SHA256 alone has no widely-cited
       standalone KAT -- see kernel/crypto.c's header comment) */
    static const u8 prf_expect[48] = {
        0x41,0x41,0x4f,0x93,0x5d,0x2b,0xb6,0x9b,0x81,0x46,0x36,0xa4,0x48,0xde,0x66,0x1f,
        0x9f,0xb8,0x69,0xcb,0x36,0x4c,0xa0,0xed,0x03,0x10,0xac,0xc2,0x5c,0xbe,0x00,0x6e,
        0x45,0xdd,0xa1,0x8e,0xa4,0x69,0x7c,0x0c,0x9f,0x34,0xa3,0xa3,0x10,0x0c,0x14,0x3b,
    };
    u8 seed[64];
    for (int i = 0; i < 32; i++)
        seed[i] = (u8)i;
    for (int i = 0; i < 32; i++)
        seed[32 + i] = (u8)(32 + i);
    tls_prf((const u8 *)"test secret 0123456789abcdef", 29, "master secret",
           seed, 64, out, 48);
    if (!bytes_eq(out, prf_expect, 48))
        return false;

    /* AES-128, FIPS-197 Appendix B's own worked example */
    static const u8 aes_key[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
    };
    static const u8 aes_pt[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff,
    };
    static const u8 aes_ct[16] = {
        0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a,
    };
    aes128_ctx_t actx;
    aes128_set_key(&actx, aes_key);
    aes128_encrypt_block(&actx, aes_pt, out);
    if (!bytes_eq(out, aes_ct, 16))
        return false;

    /* AES-128-GCM, the trivial all-zero case -- this specific tag is
       the well-known published NIST GCM "Test Case 1" value, not just
       something this codebase generated for itself */
    static const u8 gcm_zero_key[16] = {0};
    static const u8 gcm_zero_iv[12] = {0};
    static const u8 gcm_tag1_expect[16] = {
        0x58,0xe2,0xfc,0xce,0xfa,0x7e,0x30,0x61,0x36,0x7f,0x1d,0x57,0xa4,0xe7,0x45,0x5a,
    };
    u8 gcm_tag[16];
    aes128_set_key(&actx, gcm_zero_key);
    aes128_gcm_encrypt(&actx, gcm_zero_iv, NULL, 0, NULL, 0, NULL, gcm_tag);
    if (!bytes_eq(gcm_tag, gcm_tag1_expect, 16))
        return false;

    /* AES-128-GCM round trip + the negative cases that actually matter
       for TLS record-layer safety: a tampered ciphertext, tag, or AAD
       must all be rejected before any plaintext is trusted -- these
       don't need an external published vector, since "decrypt(encrypt(x))
       == x, and every single-bit corruption is caught" is a
       self-contained property checked against this file's own
       encrypt function, not a second implementation. */
    static const u8 gcm_key[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
    };
    static const u8 gcm_iv[12] = {
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,
    };
    static const u8 gcm_aad[8] = {0xa0,0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0xa7};
    static const u8 gcm_pt[20] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,
        0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,0x10,0x11,0x12,0x13,
    };
    u8 gcm_ct[20], gcm_tag2[16], gcm_pt_out[20];
    aes128_set_key(&actx, gcm_key);
    aes128_gcm_encrypt(&actx, gcm_iv, gcm_aad, sizeof(gcm_aad), gcm_pt,
                       sizeof(gcm_pt), gcm_ct, gcm_tag2);
    if (!aes128_gcm_decrypt(&actx, gcm_iv, gcm_aad, sizeof(gcm_aad), gcm_ct,
                            sizeof(gcm_ct), gcm_tag2, gcm_pt_out))
        return false; /* a valid tag must verify */
    if (!bytes_eq(gcm_pt_out, gcm_pt, sizeof(gcm_pt)))
        return false; /* and decrypt back to the original plaintext */

    u8 bad_ct[20];
    memcpy(bad_ct, gcm_ct, sizeof(gcm_ct));
    bad_ct[0] ^= 0x01;
    if (aes128_gcm_decrypt(&actx, gcm_iv, gcm_aad, sizeof(gcm_aad), bad_ct,
                           sizeof(bad_ct), gcm_tag2, gcm_pt_out))
        return false; /* a corrupted ciphertext must NOT verify */

    u8 bad_tag[16];
    memcpy(bad_tag, gcm_tag2, 16);
    bad_tag[0] ^= 0x01;
    if (aes128_gcm_decrypt(&actx, gcm_iv, gcm_aad, sizeof(gcm_aad), gcm_ct,
                           sizeof(gcm_ct), bad_tag, gcm_pt_out))
        return false; /* a corrupted tag must NOT verify */

    u8 bad_aad[8];
    memcpy(bad_aad, gcm_aad, sizeof(gcm_aad));
    bad_aad[0] ^= 0x01;
    if (aes128_gcm_decrypt(&actx, gcm_iv, bad_aad, sizeof(bad_aad), gcm_ct,
                           sizeof(gcm_ct), gcm_tag2, gcm_pt_out))
        return false; /* corrupted AAD must NOT verify either */

    /* bignum: mulmod + modexp, cross-checked against Python's
       arbitrary-precision pow(base, exp, mod) as an independent
       implementation of the same modular exponentiation */
    u8 bn_base_b[32], bn_exp_b[32], bn_mod_b[32], bn_out[32];
    for (int i = 0; i < 32; i++) {
        bn_base_b[i] = (u8)(i + 1);
        bn_exp_b[i] = (u8)(200 + i);
        bn_mod_b[i] = (u8)(50 + i * 3);
    }
    bn_mod_b[0] |= 0x80;
    static const u8 modexp_expect[32] = {
        0x99,0x34,0xff,0x60,0xca,0x5b,0x65,0x48,0xed,0x05,0xad,0xac,0xf1,0xfe,0x4e,0xb9,
        0x14,0x8c,0x64,0x6d,0x89,0xe8,0x59,0x88,0xc9,0x51,0xa5,0xf9,0xf3,0xbe,0xec,0x1e,
    };
    bignum_t bb, be, bm, br;
    bn_from_bytes_be(&bb, bn_base_b, 32);
    bn_from_bytes_be(&be, bn_exp_b, 32);
    bn_from_bytes_be(&bm, bn_mod_b, 32);
    bn_modexp(&br, &bb, &be, &bm);
    bn_to_bytes_be(&br, bn_out, 32);
    if (!bytes_eq(bn_out, modexp_expect, 32))
        return false;

    /* bignum: modular inverse via Fermat, against P-256's real field
       prime -- a * modinv(a, p) mod p must be exactly 1 */
    static const u8 p256_prime_b[32] = {
        0xff,0xff,0xff,0xff,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
        0x00,0x00,0x00,0x00,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,
    };
    bignum_t p256, av, avinv, one_check;
    bn_from_bytes_be(&p256, p256_prime_b, 32);
    bn_zero(&av);
    av.limb[0] = 12345;
    bn_modinv_prime(&avinv, &av, &p256);
    bn_mulmod(&one_check, &av, &avinv, &p256);
    bignum_t bn_one;
    bn_zero(&bn_one);
    bn_one.limb[0] = 1;
    if (bn_cmp(&one_check, &bn_one) != 0)
        return false;

    /* bignum: add + byte round-trip */
    bignum_t bx, by, bsum;
    bn_zero(&bx);
    bx.limb[0] = 0xFFFFFFFF;
    bx.limb[1] = 0x1;
    bn_zero(&by);
    by.limb[0] = 0x1;
    u32 bn_carry = bn_add(&bsum, &bx, &by);
    if (bn_carry != 0 || bsum.limb[0] != 0 || bsum.limb[1] != 2)
        return false;

    u8 rt_in[32], rt_out[32];
    for (int i = 0; i < 32; i++)
        rt_in[i] = (u8)(i * 7 + 1);
    bignum_t rt;
    bn_from_bytes_be(&rt, rt_in, 32);
    bn_to_bytes_be(&rt, rt_out, 32);
    if (!bytes_eq(rt_out, rt_in, 32))
        return false;
    if (bn_is_zero(&rt))
        return false;
    bignum_t bn_zero_check;
    bn_zero(&bn_zero_check);
    if (!bn_is_zero(&bn_zero_check))
        return false;

    return true;
}
