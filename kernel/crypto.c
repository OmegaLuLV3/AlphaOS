static u32 rotr32(u32 x, u32 n) { return (x >> n) | (x << (32 - n)); }

static void sha256_block(sha256_ctx_t *ctx, const u8 *block)
{
    u32 w[64];
    for (int i = 0; i < 16; i++)
        w[i] = ((u32)block[i * 4] << 24) | ((u32)block[i * 4 + 1] << 16) |
               ((u32)block[i * 4 + 2] << 8) | block[i * 4 + 3];
    for (int i = 16; i < 64; i++) {
        u32 s0 = rotr32(w[i - 15], 7) ^ rotr32(w[i - 15], 18) ^ (w[i - 15] >> 3);
        u32 s1 = rotr32(w[i - 2], 17) ^ rotr32(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    u32 a = ctx->h[0], b = ctx->h[1], c = ctx->h[2], d = ctx->h[3];
    u32 e = ctx->h[4], f = ctx->h[5], g = ctx->h[6], h = ctx->h[7];
    for (int i = 0; i < 64; i++) {
        u32 s1 = rotr32(e, 6) ^ rotr32(e, 11) ^ rotr32(e, 25);
        u32 ch = (e & f) ^ ((~e) & g);
        u32 t1 = h + s1 + ch + sha256_k[i] + w[i];
        u32 s0 = rotr32(a, 2) ^ rotr32(a, 13) ^ rotr32(a, 22);
        u32 maj = (a & b) ^ (a & c) ^ (b & c);
        u32 t2 = s0 + maj;
        h = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
    }
    ctx->h[0] += a; ctx->h[1] += b; ctx->h[2] += c; ctx->h[3] += d;
    ctx->h[4] += e; ctx->h[5] += f; ctx->h[6] += g; ctx->h[7] += h;
}

void sha256_init(sha256_ctx_t *ctx)
{
    static const u32 h0[8] = {
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
        0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
    };
    memcpy(ctx->h, h0, sizeof(h0));
    ctx->buf_len = 0;
    ctx->total_len = 0;
}

void sha256_update(sha256_ctx_t *ctx, const u8 *data, u64 len)
{
    ctx->total_len += len;
    while (len > 0) {
        u32 n = 64 - ctx->buf_len;
        if (n > len)
            n = (u32)len;
        memcpy(ctx->buf + ctx->buf_len, data, n);
        ctx->buf_len += n;
        data += n;
        len -= n;
        if (ctx->buf_len == 64) {
            sha256_block(ctx, ctx->buf);
            ctx->buf_len = 0;
        }
    }
}

void sha256_final(sha256_ctx_t *ctx, u8 out[32])
{
    /* captured before the padding below runs more sha256_update()
       calls that would otherwise corrupt total_len's meaning */
    u64 bitlen = ctx->total_len * 8;
    u8 pad = 0x80;
    sha256_update(ctx, &pad, 1);
    u8 zero = 0;
    while (ctx->buf_len != 56)
        sha256_update(ctx, &zero, 1);
    u8 lenbuf[8];
    for (int i = 0; i < 8; i++)
        lenbuf[i] = (u8)(bitlen >> (56 - i * 8));
    memcpy(ctx->buf + 56, lenbuf, 8);
    sha256_block(ctx, ctx->buf);
    for (int i = 0; i < 8; i++) {
        out[i * 4]     = (u8)(ctx->h[i] >> 24);
        out[i * 4 + 1] = (u8)(ctx->h[i] >> 16);
        out[i * 4 + 2] = (u8)(ctx->h[i] >> 8);
        out[i * 4 + 3] = (u8)(ctx->h[i]);
    }
}

void sha256(const u8 *data, u32 len, u8 out[32])
{
    sha256_ctx_t ctx;
    sha256_init(&ctx);
    sha256_update(&ctx, data, len);
    sha256_final(&ctx, out);
}

/* ---- HMAC-SHA256 (RFC 2104 / FIPS 198-1) ----------------------------- */

void hmac_sha256(const u8 *key, u32 key_len, const u8 *data, u32 data_len,
                 u8 out[32])
{
    u8 k[64];
    memset(k, 0, 64);
    if (key_len > 64)
        sha256(key, key_len, k);
    else
        memcpy(k, key, key_len);

    u8 ipad[64], opad[64];
    for (int i = 0; i < 64; i++) {
        ipad[i] = k[i] ^ 0x36;
        opad[i] = k[i] ^ 0x5c;
    }

    u8 inner[32];
    sha256_ctx_t ctx;
    sha256_init(&ctx);
    sha256_update(&ctx, ipad, 64);
    sha256_update(&ctx, data, data_len);
    sha256_final(&ctx, inner);

    sha256_init(&ctx);
    sha256_update(&ctx, opad, 64);
    sha256_update(&ctx, inner, 32);
    sha256_final(&ctx, out);
}

/* HMAC over two concatenated buffers without materializing the
   concatenation -- avoids a variable-length temp buffer for the
   PRF's repeated "A(i) + seed" inputs below */
static void hmac_sha256_2(const u8 *key, u32 key_len, const u8 *d1, u32 l1,
                          const u8 *d2, u32 l2, u8 out[32])
{
    u8 k[64];
    memset(k, 0, 64);
    if (key_len > 64)
        sha256(key, key_len, k);
    else
        memcpy(k, key, key_len);

    u8 ipad[64], opad[64];
    for (int i = 0; i < 64; i++) {
        ipad[i] = k[i] ^ 0x36;
        opad[i] = k[i] ^ 0x5c;
    }

    u8 inner[32];
    sha256_ctx_t ctx;
    sha256_init(&ctx);
    sha256_update(&ctx, ipad, 64);
    sha256_update(&ctx, d1, l1);
    sha256_update(&ctx, d2, l2);
    sha256_final(&ctx, inner);

    sha256_init(&ctx);
    sha256_update(&ctx, opad, 64);
    sha256_update(&ctx, inner, 32);
    sha256_final(&ctx, out);
}

/* ---- TLS 1.2 PRF (RFC 5246 section 5, P_SHA256 only -- TLS 1.2's
   cipher suites all specify SHA-256 as the PRF hash unless a suite
   says otherwise, and this only ever targets SHA-256-based suites) */

void tls_prf(const u8 *secret, u32 secret_len, const char *label,
            const u8 *seed, u32 seed_len, u8 *out, u32 out_len)
{
    /* label+seed is P_hash's own "seed" argument; 128 bytes covers
       every TLS 1.2 use here (the longest is the Finished-message
       verify_data derivation: a short label plus a 32-byte SHA-256
       handshake-transcript hash, and master-secret derivation, whose
       seed is two 32-byte randoms) with room to spare */
    u8 lseed[128];
    u32 label_len = (u32)strlen(label);
    if (label_len + seed_len > sizeof(lseed))
        return; /* never happens for this file's fixed-size callers */
    memcpy(lseed, label, label_len);
    memcpy(lseed + label_len, seed, seed_len);
    u32 lseed_len = label_len + seed_len;

    u8 a[32];
    hmac_sha256(secret, secret_len, lseed, lseed_len, a); /* A(1) */

    u32 done = 0;
    while (done < out_len) {
        u8 block[32];
        hmac_sha256_2(secret, secret_len, a, 32, lseed, lseed_len, block);
        u32 n = out_len - done < 32 ? out_len - done : 32;
        memcpy(out + done, block, n);
        done += n;
        if (done < out_len) {
            u8 next_a[32];
            hmac_sha256(secret, secret_len, a, 32, next_a);
            memcpy(a, next_a, 32);
        }
    }
}

