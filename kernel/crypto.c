/*
 * kernel/crypto.c — the cryptographic primitives TLS is built on:
 * SHA-256, HMAC-SHA256, the TLS 1.2 PRF (RFC 5246 section 5), and
 * AES-128-GCM (NIST SP 800-38D) -- the record-layer AEAD cipher for
 * TLS_ECDHE_RSA_WITH_AES_128_GCM_SHA256.
 *
 * Every primitive here was implemented against its specification and
 * independently verified against known-answer test vectors *before*
 * being adapted into this file — not just "it compiles." SHA-256
 * against NIST's published vectors, HMAC-SHA256 against RFC 4231, the
 * PRF cross-checked against a from-scratch Python reimplementation of
 * the same RFC 5246 construction, AES-128 against FIPS-197's own
 * worked example plus independently-generated vectors cross-checked
 * against OpenSSL, and GCM against vectors cross-checked against
 * PyCryptodome (whose empty-message/all-zero-key tag independently
 * reproduces the well-known published NIST GCM test case 1 value,
 * confirming that reference implementation itself is trustworthy) --
 * including negative tests confirming a tampered ciphertext, tag, or
 * AAD is correctly *rejected*, not just that valid data round-trips.
 *
 * Crypto bugs are a different class of risk from the rest of this
 * kernel: a wrong PE loader bound check crashes visibly, but a wrong
 * hash, PRF, or cipher can produce output that looks plausible and is
 * silently insecure. This file's own development caught exactly that
 * shape of bug twice — a hand-transcribed test string with a
 * one-character length error that produced a wrong-but-plausible-
 * looking HMAC output, not a compile error or a crash — which is
 * exactly why every vector here is either a published standard or
 * mechanically generated by a second, independent implementation,
 * never hand-copied hex. See SECURITY.md for the full verification
 * methodology and what this file deliberately does not attempt
 * (constant-time execution against timing side channels beyond the
 * GCM tag comparison — see that file for why).
 */
#include "kernel.h"

